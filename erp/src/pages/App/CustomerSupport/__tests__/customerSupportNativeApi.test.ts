// @vitest-environment node
import { execFile } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { promisify } from 'node:util';
import ts from 'typescript';
import { expect, it } from 'vitest';

it('carrega a API no Node nativo com o processador CJS produzido pelo build real e sem rede', async () => {
  const workspace = fileURLToPath(new URL('../../../../../../', import.meta.url));
  const scratch = join(workspace, 'scratch');
  mkdirSync(scratch, { recursive: true });
  const output = mkdtempSync(join(scratch, 'support-native-esm-'));
  const sources = ['erp/api/whatsapp-webhook.ts', 'api/whatsapp-webhook.ts', 'api/whatsapp-media.ts',
    'api/supabaseSecretKey.ts', 'erp/api/secure-integrations.ts', 'erp/api/_lib/authenticatedErpRequest.ts',
    'erp/src/pages/utils/metaService/metaGraphProxyPolicy.ts', 'erp/src/pages/utils/customerSupport/whatsappMediaProxy.ts',
    'erp/src/pages/utils/customerSupport/whatsappWebhookProcessor.ts',
    'erp/src/pages/utils/customerSupport/customerMatchingService.ts',
    'erp/src/pages/utils/customerSupport/phoneUtils.ts', 'shared-utils/withTimeout.ts'];
  // Compile the public entries without bundling. Only the processor crosses the
  // explicit CJS boundary generated by the same script used in production.
  const nativeEntries = new Set(['erp/api/whatsapp-webhook.ts', 'api/whatsapp-webhook.ts',
    'api/whatsapp-media.ts', 'api/supabaseSecretKey.ts',
    'erp/src/pages/utils/customerSupport/whatsappMediaProxy.ts']);
  for (const source of sources) {
    const original = join(output, source);
    mkdirSync(dirname(original), { recursive: true });
    writeFileSync(original, readFileSync(join(workspace, source)));
    if (!nativeEntries.has(source)) continue;
    const target = join(output, source.replace(/\.ts$/, '.js'));
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, ts.transpileModule(readFileSync(join(workspace, source), 'utf8'), {
      compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, esModuleInterop: true },
    }).outputText, 'utf8');
  }
  for (const file of ['package.json', 'erp/package.json']) {
    writeFileSync(join(output, file), readFileSync(join(workspace, file)));
  }
  symlinkSync(join(workspace, 'erp/node_modules'), join(output, 'node_modules'), 'junction');
  const environment: NodeJS.ProcessEnv = { PATH: process.env.PATH, SystemRoot: process.env.SystemRoot,
    NODE_ENV: 'production', VERCEL_ENV: 'production' };
  const builder = join(output, 'erp/scripts/build-customer-support.cjs');
  mkdirSync(dirname(builder), { recursive: true });
  writeFileSync(builder, readFileSync(join(workspace, 'erp/scripts/build-customer-support.cjs')));
  await promisify(execFile)(process.execPath, [builder], {
    cwd: output, env: environment, encoding: 'utf8', timeout: 20_000, windowsHide: true,
  });
  expect(existsSync(join(output, 'erp/src/pages/utils/customerSupport/whatsappWebhookProcessor.js'))).toBe(false);
  expect(existsSync(join(output, 'shared-utils/withTimeout.js'))).toBe(false);
  const entry = (file: string) => JSON.stringify(pathToFileURL(join(output, file)).href);
  const script = `
    let fetches = 0;
    globalThis.fetch = () => { fetches++; throw new Error('Network forbidden in native startup proof.'); };
    const erp = await import(${entry('erp/api/whatsapp-webhook.js')});
    const media = await import(${entry('api/whatsapp-media.js')});
    const webhook = await import(${entry('api/whatsapp-webhook.js')});
    const processor = (await import(${entry('erp/server/customer-support/whatsapp-processor.cjs')})).default;
    const { createHmac } = await import('node:crypto');
    const signature = 'sha256=' + createHmac('sha256', 'native-test-secret').update('{}').digest('hex');
    const signatureWorks = processor.verifyMetaSignature('{}', signature, 'native-test-secret');
    const emptyPayload = await processor.processWhatsAppWebhookPayload({}, { entry: [] });
    const invoke = async (handler, request) => {
      const response = { code: 0, setHeader() {}, status(code) { this.code = code; return this; },
        json() { return this; }, send() { return this; }, end() { return this; } };
      await handler(request, response);
      return response.code;
    };
    const results = [
      await invoke(erp.default, { method: 'GET', headers: {}, query: { operation: 'media', id: '12345' } }),
      await invoke(erp.default, { method: 'POST', headers: {}, query: { operation: 'dispatch' } }),
      await invoke(media.default, { method: 'GET', headers: {}, query: { id: '12345' } }),
      await invoke(webhook.default, { method: 'POST', headers: {}, query: {} })
    ];
    console.log(JSON.stringify({ results, fetches, signatureWorks, processedMessages: emptyPayload.processedMessages }));
  `;
  const { stdout } = await promisify(execFile)(process.execPath, ['--input-type=module', '--eval', script], {
    cwd: output, env: environment, encoding: 'utf8', timeout: 20_000, windowsHide: true,
  });
  expect(JSON.parse(stdout.trim().split(/\r?\n/).at(-1)!)).toEqual({ results: [401, 403, 401, 503], fetches: 0,
    signatureWorks: true, processedMessages: 0 });
  // Keep only compiled source in ignored scratch for diagnosis; no credentials or database fixtures.
}, 30_000);
